const catalogs: Record<Locale, Record<MessageKey, string>> = { es, en };

/** Translate a message and interpolate its named values. */
export function t(
  key: MessageKey,
  values: Record<string, string | number> = {},
  locale: Locale = defaultLocale,
): string {
  return catalogs[locale][key].replace(/\{(\w+)\}/g, (match, name: string) =>
    String(values[name] ?? match),
  );
}

/** Locale tag for formatting dates and numbers with Intl APIs. */
export function intlLocale(locale: Locale = defaultLocale): string {
  return locale === "es" ? "es-CO" : "en-US";
}
